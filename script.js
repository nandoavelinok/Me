/* =========================================================
   4. GESTÃO DE TEMA (CLARO/ESCURO)
========================================================= */
function initTheme() {
    const savedTheme = localStorage.getItem("portfolio-theme");
    const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
    const initialTheme = savedTheme || (prefersDark ? "dark" : "light");
    
    html.dataset.theme = initialTheme;
    updateThemeIcon();
}

function updateThemeIcon() {
    const moon = themeToggle.querySelector(".moon");
    const sun = themeToggle.querySelector(".sun");
    const isDark = html.dataset.theme === "dark";
    
    moon.classList.toggle("hidden", isDark);
    sun.classList.toggle("hidden", !isDark);
}

function toggleTheme() {
    const nextTheme = html.dataset.theme === "dark" ? "light" : "dark";
    html.dataset.theme = nextTheme;
    localStorage.setItem("portfolio-theme", nextTheme);
    updateThemeIcon();
}

initTheme();
themeToggle.addEventListener("click", toggleTheme);

/* =========================================================
   5. GESTÃO DE IDIOMA (PT/EN)
========================================================= */
let currentLanguage = localStorage.getItem("portfolio-language") || "pt";

function translatePage() {
    const elements = document.querySelectorAll("[data-i18n]");
    
    elements.forEach(element => {
        const key = element.dataset.i18n;
        const translation = translations[currentLanguage][key];
        
        if (translation) {
            element.textContent = translation;
        }
    });
    
    // Atualiza o atributo lang do HTML
    html.lang = currentLanguage === "pt" ? "pt-AO" : "en";
    
    // Atualiza o texto do botão de idioma
    languageText.textContent = currentLanguage === "pt" ? "PT" : "EN";
}

function toggleLanguage() {
    currentLanguage = currentLanguage === "pt" ? "en" : "pt";
    localStorage.setItem("portfolio-language", currentLanguage);
    translatePage();
}

translatePage();
languageToggle.addEventListener("click", toggleLanguage);

/* =========================================================
   6. NAVEGAÇÃO SPA (SINGLE PAGE APPLICATION)
========================================================= */
function showSection(sectionId, updateHash = true) {
    const targetSection = document.getElementById(sectionId);
    
    if (!targetSection) return;
    
    // Remove a classe active de todas as seções
    sections.forEach(section => {
        section.classList.remove("active");
    });
    
    // Adiciona a classe active à seção alvo
    targetSection.classList.add("active");
    
    // Atualiza o estado ativo dos botões de navegação
    navButtons.forEach(button => {
        const isActive = button.dataset.section === sectionId;
        button.classList.toggle("active", isActive);
        
        // Atualiza aria-current para acessibilidade
        if (isActive) {
            button.setAttribute("aria-current", "page");
        } else {
            button.removeAttribute("aria-current");
        }
    });
    
    // Atualiza o hash da URL se necessário
    if (updateHash) {
        history.pushState(null, "", `#${sectionId}`);
    }
    
    // Rola para o topo da página
    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
}

// Adiciona event listeners a todos os botões de navegação
navButtons.forEach(button => {
    button.addEventListener("click", () => {
        const sectionId = button.dataset.section;
        showSection(sectionId);
    });
});

/* =========================================================
   7. CARREGAMENTO INICIAL E NAVEGAÇÃO POR HASH
========================================================= */
function loadFromHash() {
    const hash = window.location.hash.replace("#", "");
    
    if (hash && document.getElementById(hash)) {
        showSection(hash, false);
    } else {
        showSection("inicio", false);
    }
}

// Escuta mudanças no histórico do navegador
window.addEventListener("popstate", loadFromHash);
window.addEventListener("hashchange", loadFromHash);

// Carrega a seção inicial
loadFromHash();

/* =========================================================
   8. BOTÃO VOLTAR AO TOPO
========================================================= */
function handleScrollTopVisibility() {
    const shouldShow = window.scrollY > 400;
    scrollTopBtn.classList.toggle("show", shouldShow);
}

function scrollToTop() {
    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
}

window.addEventListener("scroll", handleScrollTopVisibility, { passive: true });
scrollTopBtn.addEventListener("click", scrollToTop);

/* =========================================================
   9. DEMOS DOS PROJETOS
========================================================= */
function handleDemoClick(event) {
    const button = event.currentTarget;
    const href = button.getAttribute("href");
    
    if (href === "#") {
        event.preventDefault();
        
        const message = currentLanguage === "pt"
            ? "A demo deste projeto será adicionada em breve."
            : "The demo for this project will be added soon.";
        
        alert(message);
    }
}

document.querySelectorAll("[data-demo]").forEach(button => {
    button.addEventListener("click", handleDemoClick);
});

/* =========================================================
   10. ATALHO DE TECLADO (ESC PARA VOLTAR AO INÍCIO)
========================================================= */
function handleKeydown(event) {
    if (event.key === "Escape") {
        showSection("inicio");
    }
}

document.addEventListener("keydown", handleKeydown);

